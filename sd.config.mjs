// Build tokens/*.json (DTCG) into src/styles/tokens.css.
//
//   npm run tokens:build
//
// Two passes: core + light, core + dark. Only semantic `color.*` tokens are emitted.
// Light goes in `@theme static` (Tailwind v4 defaults), dark overrides under `.dark`.
// Values stay as raw hsl() strings: scripts/contrast.mjs parses that format.
import { writeFileSync } from 'node:fs'
import StyleDictionary from 'style-dictionary'

const OUT = 'src/styles/tokens.css'

async function declarations(theme) {
  const sd = new StyleDictionary({
    source: ['tokens/core.json', `tokens/${theme}.json`],
    log: { verbosity: 'silent' },
    platforms: { css: { transforms: ['name/kebab'] } },
  })
  const dictionary = await sd.getPlatformTokens('css')
  return dictionary.allTokens
    .filter((token) => token.path[0] === 'color')
    .map((token) => `  --${token.name}: ${token.$value ?? token.value};`)
    .join('\n')
}

const css = `/*
 * GENERATED by sd.config.mjs from tokens/*.json. Do not edit.
 * Change a token in tokens/, then run \`npm run tokens:build\`.
 */

@theme static {
${await declarations('light')}
}

.dark {
${await declarations('dark')}
}
`

writeFileSync(OUT, css)
console.log(`wrote ${OUT}`)
